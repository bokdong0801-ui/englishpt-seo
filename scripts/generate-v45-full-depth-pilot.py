    if len(files) != 35:
        raise RuntimeError(f"expected 35 source pages, found {len(files)}")
    generated = {}
    manifest_files = []
    for path in files:
        slug, intent = find_slug_intent(path.name)
        loc, profile = LOCALITIES[slug], PROFILES[intent]
        cards, steps, proofs, original_feedback = extract_source(path)
        raw = render_page(slug, loc, intent, profile, cards, steps, proofs, original_feedback)
