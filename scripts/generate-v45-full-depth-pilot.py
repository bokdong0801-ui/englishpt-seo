def esc(text: str) -> str:
    return html.escape(str(text), quote=True)

def last_hangul(text: str):
    for ch in reversed(text.strip()):
        code = ord(ch)
        if 0xAC00 <= code <= 0xD7A3:
            jong = (code - 0xAC00) % 28
            return jong != 0, jong == 8
    return False, False

def josa(text: str, pair: str) -> str:
    pairs = {
        "은/는": ("은", "는"), "이/가": ("이", "가"),
        "을/를": ("을", "를"), "과/와": ("과", "와"),
        "이나/나": ("이나", "나"),
    }
    has, rieul = last_hangul(text)
    if pair == "으로/로":
        return text + ("으로" if has and not rieul else "로")
    a, b = pairs[pair]
    return text + (a if has else b)

def extract_source(path: Path):
    raw = path.read_text(encoding="utf-8")
    cards = re.findall(r'<article class="card"><b>(.*?)</b><p>(.*?)</p>.*?</article>', raw, re.S)
    cards = [(html.unescape(re.sub(r"<.*?>", "", a)).strip(), html.unescape(re.sub(r"<.*?>", "", b)).strip()) for a, b in cards[:4]]
    steps = re.findall(r'<li><span>\d+</span><div><b>(.*?)</b><p>.*?</p></div></li>', raw, re.S)
    steps = [html.unescape(re.sub(r"<.*?>", "", x)).strip() for x in steps[:5]]
    proofs = re.findall(r'<li><b>(.*?)</b><span>.*?</span></li>', raw, re.S)
    proofs = [html.unescape(re.sub(r"<.*?>", "", x)).strip() for x in proofs[:6]]
    feedback = re.search(r'<div class="feedback">.*?<p>(.*?)</p>', raw, re.S)
    feedback = html.unescape(re.sub(r"<.*?>", "", feedback.group(1))).strip() if feedback else ""
    if len(cards) != 4 or len(steps) != 5 or len(proofs) != 6:
        raise RuntimeError(f"source extraction failed: {path.name} cards={len(cards)} steps={len(steps)} proofs={len(proofs)}")
    return cards, steps, proofs, feedback

